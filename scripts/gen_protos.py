"""Generate or verify the gRPC stubs of the gateway protocols the standalone service speaks.

The ``.proto`` files in ``services/standalone/donkit_guard_standalone/proto`` are copied from
agentgateway (Apache-2.0, see THIRD_PARTY_NOTICES.md): Envoy's ``ext_proc.v3`` as agentgateway
trims it, the shared Envoy types it imports, and agentgateway's own ``ext_mcp``. The Python
modules next to them are derived data, generated by ``grpc_tools.protoc`` with the imports
between them made package-relative. CI runs ``--check`` so they cannot drift from the sources.

    poetry run python scripts/gen_protos.py --write   # regenerate the committed modules
    poetry run python scripts/gen_protos.py --check   # exit 1 when a committed module differs
"""

from __future__ import annotations

import argparse
import re
import sys
import tempfile
from importlib import resources
from pathlib import Path

from grpc_tools import protoc

ROOT = Path(__file__).resolve().parent.parent
PROTO_DIR = ROOT / "services" / "standalone" / "donkit_guard_standalone" / "proto"
PROTOS = ("shared_envoy.proto", "ext_proc.proto", "ext_mcp.proto")
REGENERATE = "poetry run python scripts/gen_protos.py --write"
HEADER = (
    "# Generated by scripts/gen_protos.py from the .proto file of the same name. Do not edit.\n"
)
# protoc writes `import shared_envoy_pb2 as ...`; inside a package the sibling module is relative.
_SIBLING_IMPORT = re.compile(r"^import (\w+_pb2) as ", re.MULTILINE)


def _generate(out_dir: Path) -> dict[str, str]:
    include = str(resources.files("grpc_tools") / "_proto")
    args = [
        "grpc_tools.protoc",
        f"-I{PROTO_DIR}",
        f"-I{include}",
        f"--python_out={out_dir}",
        f"--pyi_out={out_dir}",
        f"--grpc_python_out={out_dir}",
        *(str(PROTO_DIR / name) for name in PROTOS),
    ]
    if protoc.main(args) != 0:
        raise SystemExit("protoc failed")
    generated: dict[str, str] = {}
    for path in sorted(out_dir.iterdir()):
        text = _SIBLING_IMPORT.sub(r"from . import \1 as ", path.read_text("utf-8"))
        generated[path.name] = HEADER + text
    return generated


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    options = parser.parse_args(argv)
    with tempfile.TemporaryDirectory() as tmp:
        generated = _generate(Path(tmp))
    if options.write:
        for name, text in generated.items():
            (PROTO_DIR / name).write_text(text, "utf-8")
        return 0
    stale = [
        name
        for name, text in generated.items()
        if not (PROTO_DIR / name).exists() or (PROTO_DIR / name).read_text("utf-8") != text
    ]
    if stale:
        print(f"stale generated modules: {', '.join(stale)}; run {REGENERATE}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
